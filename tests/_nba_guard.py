"""Skip guards for tests that need the generated NBA dataset.

``sports/nba/data/`` is gitignored: the SQLite DB and the frozen evidence JSON are
produced by the ingest pipeline, not committed. A fresh clone therefore has no NBA
data, and these tests used to FAIL with ``no such table: games`` or ``missing frozen
artifact`` — which reads to a reviewer as a broken suite.

They now skip with an explicit reason. CI stays honest: a green check means
"everything that can run on a clean clone passed", and the skip message says what
to run to enable the rest.
"""

from pathlib import Path

import sqlite3

ROOT = Path(__file__).resolve().parents[1]
NBA_DATA = ROOT / "sports" / "nba" / "data"
NBA_DB = NBA_DATA / "nba.sqlite"

REQUIRED_TABLES = {"games", "features"}


def _tables(path: Path) -> set[str]:
    """Tables in the DB, or empty set if it is missing, 0-byte, or unreadable.

    Presence is not readiness: a 0-byte ``nba.sqlite`` left behind by an import
    still exists on disk and used to pass a naive ``exists()`` check.
    """
    if not path.is_file() or path.stat().st_size == 0:
        return set()
    try:
        con = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    except sqlite3.Error:
        return set()
    try:
        return {r[0] for r in con.execute("select name from sqlite_master where type='table'")}
    except sqlite3.Error:
        return set()
    finally:
        con.close()


DATA_READY = REQUIRED_TABLES <= _tables(NBA_DB)
ARTIFACTS_READY = NBA_DATA.is_dir() and any(NBA_DATA.glob("*.json"))

DATA_REASON = (
    "needs the ingested NBA dataset (sports/nba/data/nba.sqlite with games/features "
    "tables), which is gitignored and generated by the ingest pipeline; run the NBA "
    "ingest to enable this test"
)
ARTIFACTS_REASON = (
    "needs the generated NBA evidence artifacts under sports/nba/data/, which are "
    "gitignored and produced by the NBA pipeline"
)
